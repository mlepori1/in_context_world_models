### Accuracy functions ###
def process_response_string(response):
  """Processes the response string."""
  if "[ANSWER]" in response:
    response = response.split("[ANSWER]")[-1].strip()
  try:
    response = re.findall(r"[a-zA-Z]+", response)[-1]
  except IndexError:
    print(response)
    response = ""
  return response


def compute_icwm_accuracy(results_dict, ntp=False):
  """Computes the accuracy for ICWM tasks.

  Args:
    results_dict: A dictionary containing the results of ICWM experiments.
      Expected keys include "prompt", "response", and "answer". "response"
      contains the model's output, and "answer" contains the correct answer.
    ntp: Whether the prompt is an NTP prompt.

  Returns:
    A list of integers (0 or 1), where 1 indicates a correct prediction
    and 0 indicates an incorrect prediction.
  """
  correct = []
  for problem_idx in range(len(results_dict["prompt"])):
    # Extract the response from the results object.
    response = results_dict["response"][problem_idx]
    answer = results_dict["answer"][problem_idx]
    if ntp:
      answer = [ans.strip() for ans in answer]
    else:
      answer = [answer.strip()]
    prediction = process_response_string(response)
    if prediction.strip() in answer:
      correct.append(1)
    else:
      correct.append(0)
  return np.mean(correct)


## Structure analysis functions ###


def process_structure_string(response):
  """Processes the structure string."""
  return response.split("[STRUCTURE]")[-1]


def compute_structure_accuracy(results_dict, grid_shape):
  """Computes the accuracy of the predicted structure descriptions.

  This function uses a Gemini model to auto-score whether the structure
  description generated by the model accurately describes a grid of the given
  shape.

  Args:
    results_dict: A dictionary containing the results of structure prediction
      experiments. Expected keys include "prompt" and "response". The "response"
      contains the model's generated structure description.
    grid_shape: A tuple representing the shape of the grid (e.g., (3, 3)).

  Returns:
    A list of integers (0 or 1), where 1 indicates that the generated structure
    description was deemed correct by the auto-scorer, 0 indicates incorrect.
  """

  model_url_template = "gemini-api:/models/gemini-2.5-pro"
  model_url = model_url_template.format(model_code="gemini-2.5-pro")
  client = model_client.ModelClient(
      model_url=model_url,
      default_generate_config=model_client.GenerationConfig(
          accounting_user="pair-experimental"
      ),
  )

  grid_string = "x".join(str(x) for x in grid_shape)

  correct = []
  for problem_idx in tqdm.tqdm(range(len(results_dict["prompt"]))):
    response = results_dict["response"][problem_idx]
    prediction = process_structure_string(response)
    autoscore_prompt = (
        f"The following text is supposed to describe a {grid_string} state"
        " space. Does it? Please respond only with either Yes or"
        f" No.\n{prediction}"
    )
    response = client.generate(autoscore_prompt)
    response_text = response.as_text()

    if "yes" in response_text.strip().lower():
      correct.append(1)
    else:
      correct.append(0)
  return np.mean(correct)


### Representation analysis functions ###


def _average_grid_activations(tokens2states):
  """Averages activations over all walks in a grid."""
  for token, state_dict in tokens2states.items():
    # Average the activations over all walks in the grid for this
    # token.
    tokens2states[token]["mean_activations"] = (
        state_dict["summed_activations"] / state_dict["num_instances"]
    )
    # Get rid of the summed activations to save memory.
    del tokens2states[token]["summed_activations"]
  return tokens2states


def collect_structure_activations(results_dict, world_size):
  """Collects activations for in-context representation analysis.

  Results_dict contains one entry for each question, but there are
  world_size walks per grid. Each results_dict entry contains activations
  for that walk. This function collects the activations
  for tokens over all walks on the same grid, and averages them.

  Args:
    results_dict: A dictionary containing the results, including
      "structure_activations".
    world_size: The number of walks per grid.

  Returns:
    A list of processed activations, where each element corresponds to a grid.
    Each element is a dictionary that maps tokens to a dictionary containing 
    "mean_activations" (averaged over all walks for that grid) and 
    "num_instances".
  """

  processed_tokens2states = []
  curr_tokens2states = {}

  # Iterate over all questions
  for result_idx, tokens2states in enumerate(
      results_dict["structure_activations"]
  ):
    # If we've reached the end of a set of walks corresponding to a grid,
    # average the activations and reset the running average.
    if (result_idx + 1) % world_size == 0:
      # Average activations over all walks in the grid for each token.
      curr_tokens2states = _average_grid_activations(curr_tokens2states)

      # Append to output
      processed_tokens2states.append(curr_tokens2states)

      # Reset the running averages
      curr_tokens2states = {}

    # Collect activations for this question over tokens
    for token, state_dict in tokens2states.items():
      # Init token results
      if token not in curr_tokens2states:
        if state_dict["num_instances"] > 0:
          curr_tokens2states[token] = {
              "summed_activations": (
                  state_dict["mean_activations"] * state_dict["num_instances"]
              ),
              "num_instances": state_dict["num_instances"],
          }
      # Update token results
      else:
        if state_dict["num_instances"] > 0:
          curr_tokens2states[token]["summed_activations"] += (
              state_dict["mean_activations"] * state_dict["num_instances"]
          )
          curr_tokens2states[token][
              "num_instances"
          ] += state_dict["num_instances"]
  return processed_tokens2states


def compute_dirichlet_energy(grid, tokens2states):
  """Computes the Dirichlet energy for a set of mean activations given a grid."""
  dirichlet_energy = 0.0
  normalization_factor = 0.0

  tokens2states = {
      k.strip(): v for k, v in tokens2states.items() if v["num_instances"]
  }

  for _, state_dict_1 in tokens2states.items():
    for _, state_dict_2 in tokens2states.items():
      squared_distances = torch.square(
          state_dict_1["mean_activations"] - state_dict_2["mean_activations"]
      )
      normalization_factor += torch.sum(squared_distances).item()

  for state_index in np.ndindex(grid.shape):
    state_object = grid[state_index].item()
    if state_object not in tokens2states:
      continue
    state_act = tokens2states[state_object]["mean_activations"]

    _, valid_neighbors = data_utils.get_valid_neighbors(state_index, grid)

    for neighbor in valid_neighbors:
      if neighbor not in tokens2states:  # I.E. if num_instances == 0
        continue
      neighbor_act = tokens2states[neighbor]["mean_activations"]
      squared_distances = torch.square(state_act - neighbor_act)
      dirichlet_energy += torch.sum(squared_distances).item()
  return dirichlet_energy, dirichlet_energy / normalization_factor


def compute_distance_correlation(grid, tokens2states):
  """Computes the correlation between distance in latent and grid space."""
  euclidean_distances = []
  manhattan_distances = []
  processed_pairs = set()

  tokens2states = {
      k.strip(): v for k, v in tokens2states.items() if v["num_instances"]
  }
  # Compute Manhattan and Euclidean distances for all pairs of states
  for from_index in np.ndindex(grid.shape):
    for to_index in np.ndindex(grid.shape):
      if (
          to_index,
          from_index,
      ) in processed_pairs:  # Don't process the same pair twice
        continue
      if from_index == to_index:  # Don't process the same state
        continue
      processed_pairs.add((from_index, to_index))

      from_object = grid[from_index].item()
      to_object = grid[to_index].item()
      if (
          from_object not in tokens2states
          or to_object not in tokens2states
      ):
        continue

      from_act = tokens2states[from_object]["mean_activations"]
      to_act = tokens2states[to_object]["mean_activations"]

      squared_distances = torch.square(from_act - to_act)
      euclidean_distances.append(
          torch.sqrt(torch.sum(squared_distances)).item()
      )
      manhattan_distance = np.sum(
          np.abs(np.array(from_index) - np.array(to_index))
      )
      manhattan_distances.append(manhattan_distance)

  return (
      np.corrcoef(euclidean_distances, y=manhattan_distances)[0, 1],
      euclidean_distances,
      manhattan_distances,
  )

